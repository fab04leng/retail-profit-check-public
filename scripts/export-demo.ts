/**
 * Writes the demo dataset to demo/data/*.csv and the answer key to demo/ANSWER_KEY.md.
 * Run: npm run demo:export
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { toCsv } from '../src/core/exportCsv';
import { FILE_KINDS } from '../src/core/types';
import { analyseDemo, checkAccuracy } from '../src/demo/accuracy';
import { generateDemo, DEMO_SEED } from '../src/demo/generate';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const demo = generateDemo();
mkdirSync(join(root, 'demo/data'), { recursive: true });
const files: Record<string, string> = { sales: 'sales.csv', products: 'products.csv', invoices: 'supplier-invoices.csv', payments: 'payments.csv' };
for (const k of FILE_KINDS) writeFileSync(join(root, 'demo/data', files[k]!), toCsv(demo.tables[k]));

const result = analyseDemo(demo);
const checks = checkAccuracy(demo, result);
const p = demo.planted;
const rm = (n: number) => `RM ${n.toLocaleString('en-MY', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
const f = (id: string) => result.findings.filter((x) => x.ruleId === id);
const amountOf = (ruleId: string, match: (params: Record<string, string | number>) => boolean) => f(ruleId).find((x) => match(x.params))?.amount;
const week = result.cashflow.weeks.find((w) => w.start === p.cashCrunchWeekStart);

const md = `# Demo data answer key

> **Synthetic data.** "${demo.shopName}" is invented. Supplier names are coined words, product names are generic descriptions, and there are no real businesses, people or personal data. Generated by \`src/demo/generate.ts\` with seed \`${DEMO_SEED}\`; regenerate with \`npm run demo:export\`.

**Shop:** two outlets (Jelutong, Bayan Lepas), ${demo.tables.products.length - 1} SKUs, 30 suppliers, ${demo.start} to ${demo.end} (52 weeks).
**Files:** \`demo/data/sales.csv\` (${(demo.tables.sales.length - 1).toLocaleString()} lines), \`products.csv\` (${demo.tables.products.length - 1}), \`supplier-invoices.csv\` (${(demo.tables.invoices.length - 1).toLocaleString()} lines), \`payments.csv\` (${demo.tables.payments.length - 1}).
**Patterns:** busier Fri–Sun; year-end (mid–late Dec 2025), Chinese New Year (17 Feb 2026, busiest 2 weeks before), Ramadan and Hari Raya Aidilfitri (~20 Mar 2026), festive-only products that sell only in season, about 8% growth over the year, occasional 10% discounts and refunds.
**Demo cash-flow inputs** (filled in by "Load demo data"): opening balance ${rm(demo.cashflow.openingBalance)}; ${demo.cashflow.fixedCosts.map((c) => `${c.label} ${rm(c.amount)} on day ${c.dayOfMonth}`).join('; ')}.

## Accuracy check (default rule thresholds)

| Rule | Planted issue | Planted | Found | Missed | False positives |
|---|---|---:|---:|---:|---:|
${checks.map((c) => `| ${c.ruleId} | ${c.label} | ${c.expected.length} | ${c.found.length} | ${c.missed.length} | ${c.falsePositives.length} |`).join('\n')}

This table is regenerated from the analyses each time the script runs; \`tests/accuracy/accuracy.test.ts\` fails if anything is missed or any extra finding appears. The demo data was generated to avoid borderline cases, so real files will contain more findings that turn out to be "Not an issue" after review.

## 1. Duplicate supplier invoices (6)

**Same supplier + same invoice number (SUP-01)**

| Supplier | Invoice no. | How it was planted | Value of the extra copy |
|---|---|---|---:|
${p.duplicateSameNumber.map((d) => `| ${d.supplier} | ${d.invoiceNo} | ${d.how} | ${rm(amountOf('SUP-01', (x) => x.invoiceNo === d.invoiceNo) ?? 0)} |`).join('\n')}

**Same supplier + same amount within 7 days, different invoice numbers (SUP-02)**

| Supplier | Invoice numbers | Total | Both paid? |
|---|---|---:|---|
${p.duplicateSameAmount.map((d) => `| ${d.supplier} | ${d.invoiceNos.join(' and ')} | ${rm(d.total)} | ${d.bothPaid ? 'Yes — both were paid' : 'No — the copy is unpaid and appears in the cash-flow outlook'} |`).join('\n')}

## 2. Products sold below cost (10)

| SKU | Product | Why | RM below cost (12 months) |
|---|---|---|---:|
${p.belowCost.map((b) => `| ${b.sku} | ${b.name} | ${b.reason} | ${rm(amountOf('PRF-02', (x) => x.sku === b.sku) ?? 0)} |`).join('\n')}

## 3. Dead stock — no sale for more than 90 days (25)

| SKU | Product | Why | Stock value |
|---|---|---|---:|
${p.deadStock.map((d) => `| ${d.sku} | ${d.name} | ${d.reason} | ${rm(amountOf('STK-02', (x) => x.sku === d.sku) ?? 0)} |`).join('\n')}

Also planted: ${p.slowNotDead.length} **slow but not dead** lines (last sale 65–85 days before the end): ${p.slowNotDead.map((s) => `${s.sku} ${s.name}`).join('; ')}. They count in the "slow stock" headline (no sale for more than 60 days) but are not dead-stock findings.

## 4. Supplier price increases above 5% (4)

| Supplier | SKU | Product | Increase | From |
|---|---|---|---:|---|
${p.priceJumps.map((j) => `| ${j.supplier} | ${j.sku} | ${j.name} | ${j.pct}% | ${j.date} |`).join('\n')}

Two of these (the ${p.priceJumps.filter((j) => p.belowCost.some((b) => b.sku === j.sku)).map((j) => `${j.pct}%`).join(' and ')} rises) were never passed on to the shelf price, so the products are now also sold below cost. All other cost changes in the data are under 3%.

## 5. Overpayments (2) and payments with no invoice (2)

| Supplier | Invoice no. | Type | Invoice total | Paid |
|---|---|---|---:|---:|
${p.overpaid.map((o) => `| ${o.supplier} | ${o.invoiceNo} | ${o.kind === 'paidTwice' ? 'Paid twice (same reference, 9 days apart)' : 'Paid more than the invoice (two digits swapped)'} | ${rm(o.invoiceTotal)} | ${rm(o.paid)} |`).join('\n')}

| Supplier | Payment reference | Date | Amount |
|---|---|---|---:|
${p.unmatchedPayments.map((u) => `| ${u.supplier} | ${u.reference} | ${u.date} | ${rm(u.amount)} |`).join('\n')}

## 6. Cash-crunch week (1)

With the demo inputs above and the default method, the estimated closing balance for the week of **${p.cashCrunchWeekStart}** is **${rm(week?.closing ?? 0)}**: large year-end hamper and gift-tin orders dated 20 Oct 2026 (30-day terms) fall due on 19 Nov, on top of ${rm(week?.supplierOut ?? 0)} of supplier invoices due that week in total. All other weeks stay above zero (lowest other week: ${rm(Math.min(...result.cashflow.weeks.filter((w) => w.start !== p.cashCrunchWeekStart).map((w) => w.closing)))}). This is an estimate based on the trend method, not a prediction.

## 7. Thin margins by design (${p.lowMarginByDesign.length})

Staples such as rice, sugar, flour, cooking oil, eggs, condensed milk, malt drink, diapers and formula milk were priced at 7–17% gross margin, as is common in Malaysian minimarts. They are flagged by PRF-03 (margin below the 25% target) — useful to show that a "finding" can be a deliberate choice the owner marks "Not an issue".
`;
writeFileSync(join(root, 'demo/ANSWER_KEY.md'), md);
console.log('Wrote demo/data/*.csv and demo/ANSWER_KEY.md');
console.log(checks.map((c) => `${c.ruleId} planted ${c.expected.length} found ${c.found.length} missed ${c.missed.length} fp ${c.falsePositives.length}`).join('\n'));
